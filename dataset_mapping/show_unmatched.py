"""
Print unmatched species — those missing images or missing audio.
Reads from the match report CSV generated by merging_dataset.py
"""

import pandas as pd
from pathlib import Path

REPORT_CSV = Path(r"c:\Projects\marine\datasets\species_match_report.csv")

if not REPORT_CSV.exists():
    print("❌ Report not found. Run merging_dataset.py first.")
    exit(1)

df = pd.read_csv(REPORT_CSV)

missing_images = df[df["has_image"] == False].sort_values("shared_label")
missing_audio  = df[df["has_audio"] == False].sort_values("shared_label")

print("=" * 60)
print(" 🖼  UNMATCHED — Missing Images (have audio only)")
print("=" * 60)
if len(missing_images) == 0:
    print("  ✓ All species have images!")
else:
    for i, (_, row) in enumerate(missing_images.iterrows(), 1):
        print(f"  {i:>2d}. {row['shared_label']:<35s}  (audio: {row['audio_count']})")
    print(f"\n  Total: {len(missing_images)} species missing images")

print()
print("=" * 60)
print(" 🔊 UNMATCHED — Missing Audio (have images only)")
print("=" * 60)
if len(missing_audio) == 0:
    print("  ✓ All species have audio!")
else:
    for i, (_, row) in enumerate(missing_audio.iterrows(), 1):
        print(f"  {i:>2d}. {row['shared_label']:<35s}  (images: {row['image_count']})")
    print(f"\n  Total: {len(missing_audio)} species missing audio")

print()
print("=" * 60)
matched = df[(df["has_image"] == True) & (df["has_audio"] == True)]
print(f" ✓ Matched: {len(matched)}  |  ✗ Missing img: {len(missing_images)}  |  ✗ Missing aud: {len(missing_audio)}")
print("=" * 60)
